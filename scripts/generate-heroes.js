// Scans "assets/Opening Heros/" and rewrites lib/heroImages.generated.ts with a require()
// for every picture found. These are the full-bleed backgrounds behind the once-a-day
// welcome screen.
//
// Run after adding or removing a hero image:
//   npm run sync-heroes
//
// Filenames here come straight off a phone (spaces, commas, IMG_/PXL_ prefixes) and are
// never shown to the user, so no title is derived - only the image itself matters.

const fs = require('fs');
const path = require('path');

const HERO_DIR = path.join(__dirname, '..', 'assets', 'Opening Heros');
const OUTPUT_FILE = path.join(__dirname, '..', 'lib', 'heroImages.generated.ts');

const IMAGE_EXTS = ['.jpg', '.jpeg', '.png'];

if (!fs.existsSync(HERO_DIR)) {
  console.error(`No "assets/Opening Heros" folder found at ${HERO_DIR} - create it first.`);
  process.exit(1);
}

const files = fs
  .readdirSync(HERO_DIR, { withFileTypes: true })
  .filter((f) => f.isFile() && !f.name.startsWith('.'))
  .map((f) => f.name)
  .filter((name) => {
    const ext = path.extname(name).toLowerCase();
    if (IMAGE_EXTS.includes(ext)) return true;
    console.warn(`Skipping Opening Heros/${name} - not an image ("${ext}").`);
    return false;
  })
  // Stable order so "hero of the day" stays the same picture all day, and only shifts
  // when the folder's contents actually change.
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

const header = `// ============================================================================
// AUTO-GENERATED by scripts/generate-heroes.js - DO NOT EDIT BY HAND.
// Run \`npm run sync-heroes\` after adding or removing a file in
// "assets/Opening Heros/" to regenerate this file.
// ============================================================================

/** Every opening-hero background, in a stable order. */
export const HERO_IMAGES: number[] = [
`;

const body = files.map((name) => `  require('../assets/Opening Heros/${name}'),`).join('\n');

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, `${header}${body}\n];\n`);

console.log(`Wrote ${files.length} hero image(s) to lib/heroImages.generated.ts`);
if (files.length === 0) {
  console.log('No images found - drop some into "assets/Opening Heros/" and run this again.');
}

const totalBytes = files.reduce((sum, name) => sum + fs.statSync(path.join(HERO_DIR, name)).size, 0);
const totalMb = totalBytes / 1024 / 1024;
console.log(`Total size: ${totalMb.toFixed(1)}MB`);
if (totalMb > 8) {
  console.warn(
    `WARNING: that's a lot to ship inside the app for full-screen backgrounds. These are\n` +
      `         displayed at phone size - resizing them to ~1600px on the long edge would cut\n` +
      `         this by roughly 90% with no visible difference.`
  );
}
