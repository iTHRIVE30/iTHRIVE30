// Scans assets/archive/<categoryId>/* and rewrites lib/archiveFiles.generated.ts
// with an entry (including the require() call) for every file found.
//
// Run this any time you add, remove, or rename a file in assets/archive/:
//   npm run sync-archive

const fs = require('fs');
const path = require('path');

const ARCHIVE_DIR = path.join(__dirname, '..', 'assets', 'archive');
const OUTPUT_FILE = path.join(__dirname, '..', 'lib', 'archiveFiles.generated.ts');

// If you ever need a file type that isn't here, add the extension to
// metro.config.js and archive-assets.d.ts first, then add it below too.
const KNOWN_TYPES = {
  '.pdf': 'PDF',
  '.docx': 'DOCX',
  '.doc': 'DOC',
  '.pptx': 'PPTX',
  '.xlsx': 'XLSX',
  '.zip': 'ZIP',
  // Images are Metro asset types out of the box - no metro.config.js entry needed.
  '.jpg': 'JPG',
  '.jpeg': 'JPG',
  '.png': 'PNG',
};

// File types the Archive screen shows as a picture rather than a download row.
const IMAGE_TYPES = ['JPG', 'PNG'];

// Read back the hand-maintained category list so we can warn about folders and categories
// that don't line up. A mismatch here is silent at runtime - the tab just renders empty -
// so it's worth shouting about at generate time.
function readDeclaredCategoryIds() {
  const categoriesFile = path.join(__dirname, '..', 'lib', 'archiveCategories.ts');
  if (!fs.existsSync(categoriesFile)) return null;
  const src = fs.readFileSync(categoriesFile, 'utf8');
  const listStart = src.indexOf('ARCHIVE_CATEGORIES');
  if (listStart === -1) return null;
  return [...src.slice(listStart).matchAll(/^\s*\{\s*id:\s*'([^']+)'/gm)].map((m) => m[1]);
}

function toTitle(filename) {
  const base = filename.replace(/\.[^/.]+$/, ''); // strip extension
  const withoutOrderPrefix = base.replace(/^\d+[-_]/, ''); // strip a leading "01-" ordering prefix
  return withoutOrderPrefix
    .replace(/[-_]+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function slugify(str) {
  return str.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
}

if (!fs.existsSync(ARCHIVE_DIR)) {
  console.error(`No assets/archive folder found at ${ARCHIVE_DIR} - create it first.`);
  process.exit(1);
}

const categoryFolders = fs
  .readdirSync(ARCHIVE_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const items = [];

categoryFolders.forEach((categoryId) => {
  const categoryPath = path.join(ARCHIVE_DIR, categoryId);
  const files = fs
    .readdirSync(categoryPath, { withFileTypes: true })
    .filter((f) => f.isFile() && !f.name.startsWith('.'))
    .map((f) => f.name)
    // Natural sort, so "2.jpg" comes before "10.jpg". Plain alphabetical put 10, 11, 12
    // ahead of 2 for the numbered image sets, which read as broken.
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

  files.forEach((filename, index) => {
    const ext = path.extname(filename).toLowerCase();
    const fileType = KNOWN_TYPES[ext];
    if (!fileType) {
      console.warn(`Skipping ${categoryId}/${filename} - unrecognised file type "${ext}".`);
      return;
    }
    const id = `${categoryId}-${slugify(filename.replace(/\.[^/.]+$/, ''))}`;
    items.push({
      id,
      categoryId,
      title: toTitle(filename),
      fileType,
      isImage: IMAGE_TYPES.includes(fileType),
      order: index + 1,
      requirePath: `../assets/archive/${categoryId}/${filename}`,
    });
  });
});

const header = `// ============================================================================
// AUTO-GENERATED by scripts/generate-archive.js - DO NOT EDIT BY HAND.
// Run \`npm run sync-archive\` after adding, removing, or renaming any file in
// assets/archive/ to regenerate this file.
//
// Want a nicer title, a description, or a custom order for one of these?
// Edit lib/archiveMeta.ts instead - it overrides these defaults and never
// gets touched by the generator.
// ============================================================================

export type GeneratedArchiveFile = {
  id: string;
  categoryId: string;
  title: string;
  fileType: string;
  isImage: boolean;
  order: number;
  file: number;
};

export const GENERATED_ARCHIVE_FILES: GeneratedArchiveFile[] = [
`;

const body = items
  .map(
    (item) => `  {
    id: '${item.id}',
    categoryId: '${item.categoryId}',
    title: '${item.title.replace(/'/g, "\\'")}',
    fileType: '${item.fileType}',
    isImage: ${item.isImage},
    order: ${item.order},
    file: require('${item.requirePath}'),
  },`
  )
  .join('\n');

const footer = `
];
`;

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, header + body + footer);

console.log(`Wrote ${items.length} file(s) across ${categoryFolders.length} folder(s) to lib/archiveFiles.generated.ts`);
if (items.length === 0) {
  console.log('No files found yet - drop something into assets/archive/<category>/ and run this again.');
}

const declaredIds = readDeclaredCategoryIds();
if (declaredIds) {
  const orphanFolders = categoryFolders.filter((f) => !declaredIds.includes(f));
  const emptyCategories = declaredIds.filter((id) => !categoryFolders.includes(id));

  orphanFolders.forEach((folder) => {
    const count = items.filter((i) => i.categoryId === folder).length;
    console.warn(
      `WARNING: assets/archive/${folder}/ has ${count} file(s) but no category with id '${folder}' ` +
        `in lib/archiveCategories.ts - these files will NOT appear in the app.`
    );
  });
  emptyCategories.forEach((id) => {
    console.warn(
      `WARNING: category '${id}' is declared in lib/archiveCategories.ts but there is no ` +
        `assets/archive/${id}/ folder - it will render as an empty category.`
    );
  });
  if (orphanFolders.length === 0 && emptyCategories.length === 0) {
    console.log('Categories and folders all line up.');
  }
}
